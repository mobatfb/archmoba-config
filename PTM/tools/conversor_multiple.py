    def _init_drag_drop(self):
        try:
            dnd = importlib.import_module("tkinterdnd2")
            DND_FILES = getattr(dnd, "DND_FILES")
            TkinterDnD = getattr(dnd, "TkinterDnD")
            root = self.winfo_toplevel()
            TkinterDnD._require(root)
            for widget in (self.drop_zone, self.drop_label, self.listbox):
                TkinterDnD.DnDWrapper.drop_target_register(widget, DND_FILES)
                TkinterDnD.DnDWrapper.dnd_bind(widget, "<<Drop>>", self._on_drop)
        except Exception:
            self.status_var.set("Arrastrar y soltar no disponible · haz clic para elegir archivos")

    def _on_drop(self, event):
        if self.busy:
            return "break"
        try:
            items = list(self.tk.splitlist(event.data))
        except Exception:
            items = [getattr(event, "data", "")]
        paths = [str(Path(p)) for p in items if p and Path(p).is_file()]
        if paths:
            self.set_inputs(paths, append=self.multiple_mode.get())
        return "copy"

    def browse_files(self):
        if self.busy:
            return
        if self.multiple_mode.get():
            paths = filedialog.askopenfilenames(title="Seleccionar archivos para convertir", filetypes=[("Todos los archivos", "*.*")])
            if paths:
                self.set_inputs(paths, append=True)
        else:
            path = filedialog.askopenfilename(title="Seleccionar archivo para convertir", filetypes=[("Todos los archivos", "*.*")])
            if path:
                self.set_inputs([path], append=False)

    def set_inputs(self, paths, append=False):
        files = [str(Path(p).resolve()) for p in paths if Path(p).is_file()]
        if not files:
            return
        if not self.multiple_mode.get():
            self.inputs = [files[0]]
        else:
            current = list(self.inputs) if append else []
            seen = {p.casefold() for p in current}
            for path in files:
                if path.casefold() not in seen:
                    current.append(path)
                    seen.add(path.casefold())
            self.inputs = current
        self._refresh_inputs_ui()

    def _refresh_inputs_ui(self):
        self.listbox.delete(0, "end")
        for index, path in enumerate(self.inputs, start=1):
            self.listbox.insert("end", f"{index}. {Path(path).name}")
        if not self.inputs:
            self.drop_label.configure(text="⇩  Arrastra un archivo o haz clic para buscar")
            self.status_var.set("Arrastra un archivo o haz clic para buscar")
            return
        if len(self.inputs) == 1:
            shown = Path(self.inputs[0]).name
            if len(shown) > 55:
                shown = shown[:52] + "..."
            self.drop_label.configure(text=f"✓  {shown} · Clic para cambiar")
        else:
            self.drop_label.configure(text=f"✓  {len(self.inputs)} archivos cargados")
        self.status_var.set(f"{len(self.inputs)} archivo(s) preparado(s)")

    def clear_inputs(self):
        if self.busy:
            return
        self.inputs = []
        self._refresh_inputs_ui()

    def _toggle_multiple(self):
        if self.busy:
            return
        if self.multiple_mode.get():
            self.multi_panel.grid()
        else:
            self.multi_panel.grid_remove()
            if len(self.inputs) > 1:
                self.inputs = self.inputs[:1]
                self._refresh_inputs_ui()

    def move_selected(self, delta):
        selection = self.listbox.curselection()
        if not selection:
            return
        index = int(selection[0])
        target = index + int(delta)
        if target < 0 or target >= len(self.inputs):
            return
        self.inputs[index], self.inputs[target] = self.inputs[target], self.inputs[index]
        self._refresh_inputs_ui()
        self.listbox.selection_set(target)
        self.listbox.see(target)

    def remove_selected(self):
        selection = self.listbox.curselection()
        if not selection:
            return
        index = int(selection[0])
        if 0 <= index < len(self.inputs):
            del self.inputs[index]
        self._refresh_inputs_ui()

