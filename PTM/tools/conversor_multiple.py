def _app_base():
    local = os.environ.get("LOCALAPPDATA")
    if local:
        root = Path(local) / "ARCHMOBA" / "PTM" / "conversor_multiple"
    else:
        root = Path.home() / ".archmoba" / "PTM" / "conversor_multiple"
    root.mkdir(parents=True, exist_ok=True)
    return root


def _default_output_dir():
    downloads = Path.home() / "Downloads"
    if not downloads.is_dir():
        downloads = Path.home()
    path = downloads / "ARCHMOBA Conversiones"
    path.mkdir(parents=True, exist_ok=True)
    return path


def _engine_root():
    return _app_base() / "engine" / ("engine_" + ENGINE_SHA256[:12])


def _ensure_embedded_engine():
    root = _engine_root()
    marker = root / ".ready"
    if marker.is_file():
        return root

    temp = root.with_name(root.name + ".tmp")
    shutil.rmtree(temp, ignore_errors=True)
    temp.mkdir(parents=True, exist_ok=True)

    raw = base64.b64decode(ENGINE_PAYLOAD.encode("ascii"))
    if hashlib.sha256(raw).hexdigest() != ENGINE_SHA256:
        raise RuntimeError("El motor integrado no superó la verificación de integridad.")

    with zipfile.ZipFile(__import__("io").BytesIO(raw), "r") as archive:
        for info in archive.infolist():
            name = Path(info.filename)
            if name.is_absolute() or ".." in name.parts:
                raise RuntimeError("El motor integrado contiene una ruta no válida.")
            target = temp / name
            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(archive.read(info.filename))

    marker_tmp = temp / ".ready"
    marker_tmp.write_text(ENGINE_SHA256, encoding="utf-8")
    root.parent.mkdir(parents=True, exist_ok=True)
    if root.exists():
        shutil.rmtree(root, ignore_errors=True)
    temp.replace(root)
    return root


def _unique_destination(folder, name):
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    desired = folder / name
    if not desired.exists():
        return desired
    stem = desired.stem
    suffix = desired.suffix
    index = 2
    while True:
        candidate = folder / f"{stem}_{index}{suffix}"
        if not candidate.exists():
            return candidate
        index += 1


def _managed_ptm_deps_dir():
    """Devuelve el site-packages privado que PTM usa en Linux."""
    if os.environ.get("LOCALAPPDATA"):
        return Path(os.environ["LOCALAPPDATA"]) / "ARCHMOBA" / "PTM" / "python" / "site-packages"
    return Path.home() / ".archmoba" / "PTM" / "python" / "site-packages"


def _patch_engine_pip_for_linux():
    """
    El engine original puede intentar instalar dependencias con --user e incluso
    pywin32. En Linux se redirigen esas instalaciones al entorno privado de PTM.
    """
    if os.name == "nt":
        return

    deps_dir = _managed_ptm_deps_dir()
    deps_dir.mkdir(parents=True, exist_ok=True)

    if str(deps_dir) not in sys.path:
        sys.path.insert(0, str(deps_dir))

    current_pythonpath = os.environ.get("PYTHONPATH", "")
    parts = [str(deps_dir)]
    parts.extend(
        part for part in current_pythonpath.split(os.pathsep)
        if part and part != str(deps_dir)
    )
    os.environ["PYTHONPATH"] = os.pathsep.join(parts)

    real_run = subprocess.run
    real_check_call = subprocess.check_call
    real_check_output = subprocess.check_output

    def rewrite_pip_command(command):
        if not isinstance(command, (list, tuple)):
            return command, False, False

        cmd = [str(item) for item in command]
        lowered = [item.lower() for item in cmd]

        try:
            pip_index = lowered.index("pip")
        except ValueError:
            return command, False, False

        if pip_index < 1 or lowered[pip_index - 1] != "-m":
            return command, False, False
        if "install" not in lowered[pip_index + 1:]:
            return command, False, False

        windows_only = {
            "pywin32",
            "pypiwin32",
            "win32api",
            "win32com",
            "pythoncom",
        }
        requested = {
            item.split("==", 1)[0].split(">=", 1)[0].split("<=", 1)[0].lower()
            for item in cmd
            if item and not item.startswith("-")
        }
        if requested & windows_only:
            return cmd, True, True

        clean = []
        skip_next = False
        for index, item in enumerate(cmd):
            if skip_next:
                skip_next = False
                continue

            low = item.lower()
            if low == "--user":
                continue

            if low in {"--target", "-t"}:
                skip_next = True
                continue

            clean.append(item)

        install_pos = next(
            (
                index for index, item in enumerate(clean)
                if item.lower() == "install"
            ),
            None,
        )
        if install_pos is not None:
            clean[install_pos + 1:install_pos + 1] = [
                "--upgrade",
                "--target",
                str(deps_dir),
            ]

        return clean, True, False

    def patched_run(command, *args, **kwargs):
        rewritten, is_pip, skip = rewrite_pip_command(command)
        if is_pip and skip:
            return subprocess.CompletedProcess(
                rewritten,
                0,
                stdout="" if kwargs.get("text") else b"",
                stderr="" if kwargs.get("text") else b"",
            )
        return real_run(rewritten, *args, **kwargs)

    def patched_check_call(command, *args, **kwargs):
        rewritten, is_pip, skip = rewrite_pip_command(command)
        if is_pip and skip:
            return 0
        return real_check_call(rewritten, *args, **kwargs)

    def patched_check_output(command, *args, **kwargs):
        rewritten, is_pip, skip = rewrite_pip_command(command)
        if is_pip and skip:
            return "" if kwargs.get("text") or kwargs.get("universal_newlines") else b""
        return real_check_output(rewritten, *args, **kwargs)

    subprocess.run = patched_run
    subprocess.check_call = patched_check_call
    subprocess.check_output = patched_check_output


def _child_convert(request_path):
    response_path = Path(request_path).with_suffix(".response.json")
    response = {"ok": False}
    try:
        request = json.loads(Path(request_path).read_text(encoding="utf-8"))
        mode = str(request.get("mode", ""))
        if mode not in MODES:
            raise ValueError("Modo de conversión no permitido.")

        inputs = [str(Path(p)) for p in request.get("inputs", []) if Path(p).is_file()]
        if not inputs:
            raise ValueError("No hay archivos válidos para convertir.")

        _patch_engine_pip_for_linux()

        engine_root = _ensure_embedded_engine()
        package_parent = engine_root.parent
        package_name = engine_root.name
        # Los módulos usan imports relativos, por lo que la carpeta extraída se
        # trata como un paquete Python temporal e independiente de PTM.
        if str(package_parent) not in sys.path:
            sys.path.insert(0, str(package_parent))
        service = importlib.import_module(package_name + ".service")

        result = service.convert_local_batch(mode, inputs, {})
        generated = Path(str(result.get("path", "")))
        if not generated.is_file() or generated.stat().st_size <= 0:
            raise RuntimeError("El engine no generó un archivo de salida.")

        output_dir = Path(str(request.get("output_dir") or _default_output_dir()))
        destination = _unique_destination(output_dir, str(result.get("name") or generated.name))
        shutil.copy2(generated, destination)

        response = {
            "ok": True,
            "path": str(destination),
            "name": destination.name,
            "mode": mode,
            "converted_count": int(result.get("converted_count") or 1),
            "compatible_count": int(result.get("compatible_count") or len(inputs)),
            "failed_count": int(result.get("failed_count") or 0),
            "size": int(destination.stat().st_size),
        }
    except Exception as exc:
        response = {
            "ok": False,
            "error": str(exc).strip() or exc.__class__.__name__,
        }
    try:
        response_path.write_text(json.dumps(response, ensure_ascii=False, indent=2), encoding="utf-8")
    except Exception:
        pass


